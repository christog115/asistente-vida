// Puente seguro entre la ventana y el proceso principal.
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('asistente', {
  getData: () => ipcRenderer.invoke('get-data'),
  refresh: () => ipcRenderer.invoke('refresh'),
  getStatus: () => ipcRenderer.invoke('get-status'),
  googleConnect: () => ipcRenderer.invoke('google-connect'),
  googleDisconnect: () => ipcRenderer.invoke('google-disconnect'),
  moodleSetUrl: (url) => ipcRenderer.invoke('moodle-set-url', url),
  moodleConnectPassword: (user, pass) => ipcRenderer.invoke('moodle-connect-password', user, pass),
  moodleConnectBrowser: () => ipcRenderer.invoke('moodle-connect-browser'),
  moodleDisconnect: () => ipcRenderer.invoke('moodle-disconnect'),
  canvaSetApp: (id, secret) => ipcRenderer.invoke('canva-set-app', id, secret),
  canvaConnect: () => ipcRenderer.invoke('canva-connect'),
  canvaDisconnect: () => ipcRenderer.invoke('canva-disconnect'),
  spotifySetApp: (id) => ipcRenderer.invoke('spotify-set-app', id),
  spotifyConnect: () => ipcRenderer.invoke('spotify-connect'),
  spotifyDisconnect: () => ipcRenderer.invoke('spotify-disconnect'),
  whatsappSave: (cfg) => ipcRenderer.invoke('whatsapp-save', cfg),
  whatsappTest: () => ipcRenderer.invoke('whatsapp-test'),
  whatsappDisconnect: () => ipcRenderer.invoke('whatsapp-disconnect'),
  updateSetEnabled: (on) => ipcRenderer.invoke('update-set-enabled', on),
  updateCheck: () => ipcRenderer.invoke('update-check'),
  updateInstall: () => ipcRenderer.invoke('update-install'),
  setSheetUrl: (url) => ipcRenderer.invoke('set-sheet-url', url),
  aiSetKey: (which, key) => ipcRenderer.invoke('ai-set-key', which, key),
  aiSetProvider: (p) => ipcRenderer.invoke('ai-set-provider', p),
  aiChat: (history, opts) => ipcRenderer.invoke('ai-chat', history, opts),
  voiceStatus: () => ipcRenderer.invoke('voice-status'),
  ttsSpeak: (text, voiceId) => ipcRenderer.invoke('tts-speak', text, voiceId),
  voiceSet: (changes) => ipcRenderer.invoke('voice-set', changes),
  voicePrepare: () => ipcRenderer.invoke('voice-prepare'),
  voiceState: (text) => ipcRenderer.invoke('voice-state', text),
  showWindow: () => ipcRenderer.invoke('show-window'),
  onVoiceProgress: (cb) => ipcRenderer.on('voice-progress', (_e, pct) => cb(pct)),
  onVoiceSpeak: (cb) => ipcRenderer.on('voice-speak', (_e, text) => cb(text)),
  onVoiceActivate: (cb) => ipcRenderer.on('voice-activate', () => cb()),
  aiBriefing: () => ipcRenderer.invoke('ai-briefing'),
  phoneCreate: () => ipcRenderer.invoke('phone-create'),
  phoneQr: () => ipcRenderer.invoke('phone-qr'),
  phoneSetEnabled: (on) => ipcRenderer.invoke('phone-set-enabled', on),
  phoneSetServer: (url) => ipcRenderer.invoke('phone-set-server', url),
  phoneDisable: () => ipcRenderer.invoke('phone-disable'),
  phoneTest: () => ipcRenderer.invoke('phone-test'),
  mobileSetEnabled: (on) => ipcRenderer.invoke('mobile-set-enabled', on),
  mobileStartPairing: () => ipcRenderer.invoke('mobile-start-pairing'),
  mobileRevoke: (id) => ipcRenderer.invoke('mobile-revoke', id),
  setReminders: (times) => ipcRenderer.invoke('set-reminders', times),
  setAutostart: (on) => ipcRenderer.invoke('set-autostart', on),
  onData: (cb) => ipcRenderer.on('data', (_e, data) => cb(data))
});
